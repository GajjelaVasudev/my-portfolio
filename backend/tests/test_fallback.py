def test_health_endpoints(client):
    """Test that /health and /api/health respond with 200 and healthy status."""
    res1 = client.get("/health")
    assert res1.status_code == 200
    data1 = res1.json()
    assert data1["status"] == "healthy"
    assert "service" in data1

    res2 = client.get("/api/health")
    assert res2.status_code == 200
    assert res2.json()["status"] == "healthy"


def test_dependency_health_endpoint(client):
    """Test that /health/deps reports dependency status without exposing secrets."""
    res = client.get("/health/deps")
    assert res.status_code == 200
    data = res.json()
    assert "status" in data
    assert "database" in data
    assert "configured_providers" in data
    # Ensure no secrets leaked
    assert not any("key" in str(v).lower() for v in data.values())


def test_is_valid_key_logic():
    """Verify that placeholder and missing keys are detected as invalid."""
    assert _is_valid_key(None) is False
    assert _is_valid_key("") is False
    assert _is_valid_key("short") is False
    assert _is_valid_key("your_gemini_api_key_here") is False
    assert _is_valid_key("your_openai_api_key_here") is False
    assert _is_valid_key("AIzaSyB1234567890abcdef") is True
    assert _is_valid_key("sk-proj-1234567890abcdef") is True


def test_unconfigured_providers_skipped(monkeypatch, sample_chunk):
    """If OpenAI and Groq are not configured, they are skipped automatically."""
    monkeypatch.setattr(settings, "gemini_api_key", "test_gemini_key_12345")
    monkeypatch.setattr(settings, "google_api_key", None)
    monkeypatch.setattr(settings, "openai_api_key", None)
    monkeypatch.setattr(settings, "groq_api_key", None)

    mock_resp = MagicMock()
    mock_resp.text = "Answer from Gemini primary."

    with patch("google.genai.Client") as mock_genai:
        mock_instance = MagicMock()
        mock_instance.models.generate_content.return_value = mock_resp
        mock_genai.return_value = mock_instance

